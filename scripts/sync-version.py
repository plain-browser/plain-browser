#!/usr/bin/env python3
"""Regenerate src/plainbrowser/common/version.h from [product] version in versions.toml.

usage: sync-version.py [--check]
--check exits 1 when the header is stale (used in CI). The header carries the full version
("0.1.0-alpha.1") and the numeric part ("0.1.0"), which is all that leaves the machine (see
patches/70-safebrowsing: "X-Client: PlainBrowser/0.1.0", nothing per user or per install).
"""
import re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HEADER = ROOT / "src" / "plainbrowser" / "common" / "version.h"


def product_version():
    text = (ROOT / "versions.toml").read_text(encoding="utf-8")
    m = re.search(r'(?ms)^\[product\].*?^version\s*=\s*"([^"]+)"', text)
    if not m:
        raise SystemExit("versions.toml: [product] version not found")
    return m.group(1)


def render(full):
    m = re.match(r"(\d+\.\d+\.\d+)", full)
    if not m:
        raise SystemExit("version must start with major.minor.patch: " + full)
    return """// Copyright Plain Browser contributors. MPL-2.0.
// Generated by scripts/sync-version.py from versions.toml. Do not edit.
#ifndef PLAINBROWSER_COMMON_VERSION_H_
#define PLAINBROWSER_COMMON_VERSION_H_

// Full product version, for chrome://version and logs.
#define PLAINBROWSER_VERSION_FULL "%s"
// major.minor.patch only: the part allowed in network requests.
#define PLAINBROWSER_VERSION "%s"

#endif  // PLAINBROWSER_COMMON_VERSION_H_
""" % (full, m.group(1))


def main():
    want = render(product_version())
    have = HEADER.read_text(encoding="utf-8") if HEADER.exists() else ""
    if "--check" in sys.argv:
        if have != want:
            print("%s is stale: run scripts/sync-version.py" % HEADER.relative_to(ROOT), file=sys.stderr)
            return 1
        print("version.h up to date")
        return 0
    HEADER.write_text(want, encoding="utf-8", newline="\n")
    print("wrote %s" % HEADER.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
