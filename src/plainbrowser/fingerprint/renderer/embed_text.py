#!/usr/bin/env python3
"""GN action: write a text file as a C++ `extern const char NAME[]` definition.

usage: embed_text.py <input> <output.cc> <constant name> <namespace>
The text is split into string-literal chunks so MSVC's per-literal length limit is never hit.
"""
import sys


def main(src, dst, name, ns):
    text = open(src, encoding="utf-8").read()
    chunks = []
    for line in text.splitlines(keepends=True):
        esc = line.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("?", "\\?")
        chunks.append('"%s"' % esc)
    body = "\n    ".join(chunks) or '""'
    with open(dst, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by embed_text.py from %s. Do not edit.\n" % src.replace("\\", "/"))
        f.write("namespace %s {\nextern const char %s[];\nconst char %s[] =\n    %s;\n}  // namespace %s\n"
                % (ns, name, name, body, ns))
    return 0


if __name__ == "__main__":
    if len(sys.argv) != 5:
        sys.exit(__doc__)
    sys.exit(main(*sys.argv[1:]))
